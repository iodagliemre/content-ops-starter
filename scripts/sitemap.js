/**
 * PAKET-P8 G6. Writes public/sitemap.xml (TR + EN, hreflang alternates). Runs before every build (`prebuild`), so a
 * new Bilgi Bankası article (content/{tr,en}/bilgi/*.md) is in the sitemap as soon as it is published.
 * Paths mirror content/locale.ts (kept in plain JS so the script needs no TypeScript runtime).
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SITE = 'https://doveify.io';
const today = new Date().toISOString().slice(0, 10);

const systems = [
    ['clinic-os', 'clinic-os'],
    ['brokers-brain', 'brokers-brain'],
    ['emlak-ofis-paneli', 'real-estate-office-panel'],
    ['osgb-yonetim', 'osgb-management'],
    ['kuru-temizleme', 'dry-cleaning-panel'],
    ['turkisg-ai', 'turkisg-ai']
];

/** [tr path, en path | null, lastmod] */
const pages = [
    ['/', '/en/', today],
    ...systems.map(([tr, en]) => [`/sistemler/${tr}/`, `/en/systems/${en}/`, today]),
    ['/kendi-yaziliminiz/', '/en/your-own-software/', today],
    ['/bilgi-bankasi/', '/en/knowledge-base/', today],
    ['/iletisim/', '/en/contact/', today],
    ['/gizlilik/', '/en/privacy/', today]
];

function articles(locale) {
    const dir = path.join(ROOT, 'content', locale, 'bilgi');
    if (!fs.existsSync(dir)) return new Map();
    const out = new Map();
    for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.md'))) {
        const text = fs.readFileSync(path.join(dir, file), 'utf8').replace(/\r\n/g, '\n');
        const fm = /^---\n([\s\S]*?)\n---/.exec(text);
        const attrs = {};
        (fm ? fm[1] : '').split('\n').forEach((line) => {
            const i = line.indexOf(': ');
            if (i > 0) attrs[line.slice(0, i).trim()] = line.slice(i + 2).trim();
        });
        out.set(attrs.slug || path.basename(file, '.md'), attrs.date || today);
    }
    return out;
}

const tr = articles('tr');
const en = articles('en');
for (const [slug, date] of tr) pages.push([`/bilgi-bankasi/${slug}/`, en.has(slug) ? `/en/knowledge-base/${slug}/` : null, date]);
for (const [slug, date] of en) if (!tr.has(slug)) pages.push([null, `/en/knowledge-base/${slug}/`, date]);

function entry(loc, trPath, enPath, lastmod) {
    const alts =
        trPath && enPath
            ? [
                  `    <xhtml:link rel="alternate" hreflang="tr" href="${SITE}${trPath}"/>`,
                  `    <xhtml:link rel="alternate" hreflang="en" href="${SITE}${enPath}"/>`,
                  `    <xhtml:link rel="alternate" hreflang="x-default" href="${SITE}${trPath}"/>`
              ]
            : [];
    return ['  <url>', `    <loc>${SITE}${loc}</loc>`, `    <lastmod>${lastmod}</lastmod>`, ...alts, '  </url>'].join('\n');
}

const urls = [];
for (const [trPath, enPath, lastmod] of pages) {
    if (trPath) urls.push(entry(trPath, trPath, enPath, lastmod));
    if (enPath) urls.push(entry(enPath, trPath, enPath, lastmod));
}

const xml = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Generated by scripts/sitemap.js (PAKET-P8 G6) before every build. Do not edit by hand. -->',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">',
    ...urls,
    '</urlset>',
    ''
].join('\n');

fs.writeFileSync(path.join(ROOT, 'public', 'sitemap.xml'), xml);
console.log(`sitemap.xml: ${urls.length} URLs`);
